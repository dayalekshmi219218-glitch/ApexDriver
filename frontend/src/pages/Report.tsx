import { ArrowLeft, Info } from 'lucide-react';
import { useCallback, useState } from 'react';
import { Link, useParams } from 'react-router-dom';
import { DownloadPdfButton } from '../components/DownloadPdfButton';
import { ExplainCard } from '../components/ExplainCard';
import { Gauge } from '../components/Gauge';
import { RangeBar } from '../components/RangeBar';
import { StateBar } from '../components/StateBar';
import { Button } from '../components/ui/Button';
import { EmptyState } from '../components/ui/EmptyState';
import { Chip, Pill } from '../components/ui/Pill';
import { SIGNALS } from '../lib/config';
import { fmtDateTime, fmtNum, toDisplay, unitFor } from '../lib/units';
import { rangeSummary } from '../lib/zones';
import type { Explanation, Severity, SignalSummary } from '../lib/types';
import { api } from '../services/api';
import { useStore } from '../state/store';

function TimeInBand({ s }: { s: SignalSummary }) {
  if (!s.scored || !s.available) return null;
  return (
    <div className="mt-2" title={`${Math.round(s.pctNormal)}% normal, ${Math.round(s.pctWatch)}% watch, ${Math.round(s.pctAlert)}% alert`}>
      <div className="flex h-1.5 w-full overflow-hidden rounded-full bg-surface3">
        <div className="bg-sev-normal" style={{ width: `${s.pctNormal}%` }} />
        <div className="bg-sev-watch" style={{ width: `${s.pctWatch}%` }} />
        <div className="bg-sev-alert" style={{ width: `${s.pctAlert}%` }} />
      </div>
      <div className="mt-1 text-[10px] text-muted">time in range</div>
    </div>
  );
}

export default function Report() {
  const { id } = useParams();
  const { scans, vehicles, settings, setSettings, notify } = useStore();
  const scan = scans.find((s) => s.id === id);
  const vehicle = vehicles.find((v) => v.id === scan?.vehicleId);
  const [explanation, setExplanation] = useState<Explanation | null>(null);
  const fetcher = useCallback((lv: 'simple' | 'technical') => api.explainScan(id ?? '', lv, settings), [id, settings]);

  if (!scan || !vehicle) {
    return <EmptyState icon={<Info size={24} />} title="Report not found" text="This scan may have been deleted."
      action={<Link to="/vehicles"><Button variant="soft">Back to vehicles</Button></Link>} />;
  }

  const counts: Record<Severity, number> = { normal: 0, watch: 0, alert: 0, none: 0 };
  for (const s of scan.signals) if (s.scored) counts[s.available ? s.severity : 'none']++;
  const missing = scan.signals.filter((s) => s.scored && !s.available);

  return (
    <div className="animate-fade-up space-y-6">
      <div>
        <Link to={`/vehicles/${vehicle.id}`} className="inline-flex items-center gap-1.5 text-sm text-muted hover:text-ink"><ArrowLeft size={14} /> {vehicle.name}</Link>
        <div className="mt-2 flex flex-wrap items-start justify-between gap-4">
          <div>
            <h1 className="text-3xl font-bold">Health report</h1>
            <div className="mt-1 flex flex-wrap items-center gap-2 text-muted">
              <span>{vehicle.name}{vehicle.modelYear ? ` (${vehicle.modelYear})` : ''}</span><span aria-hidden>·</span>
              <span>{fmtDateTime(scan.startedAt)}</span><span aria-hidden>·</span><span>{scan.durationMin} min</span>
              <Chip>{scan.source}</Chip>
            </div>
          </div>
          <DownloadPdfButton vehicle={vehicle} scan={scan} settings={settings} explanation={explanation} onError={(m) => notify(m, 'error')} />
        </div>
      </div>

      {scan.simulated && (
        <div className="flex items-start gap-3 rounded-xl border border-border bg-surface2/70 p-4 text-sm text-muted">
          <Info size={16} className="mt-0.5 shrink-0 text-primary" />
          Prototype: this report is generated by the in-browser simulator so the screens can be reviewed. Real parsing and scoring connect in the backend step.
        </div>
      )}

      <div className="grid gap-6 lg:grid-cols-[minmax(0,320px)_1fr]">
        <section className="card flex flex-col items-center p-6 text-center">
          <Gauge value={scan.score} severity={scan.severity} size={230} />
          <p className="mt-4 text-sm text-muted">Based on <b className="text-ink">{scan.scoredSignals} of {scan.totalSignals}</b> scored signals</p>
          <div className="mt-5 w-full text-left"><div className="label mb-2">Engine state during the log</div><StateBar states={scan.states} /></div>
        </section>
        <section className="card p-6">
          <h2 className="text-lg font-semibold">At a glance</h2>
          <div className="mt-4 grid grid-cols-2 gap-3 sm:grid-cols-4">
            {(['normal', 'watch', 'alert', 'none'] as Severity[]).map((k) => (
              <div key={k} className="rounded-xl bg-surface2 p-4">
                <div className="font-display text-3xl font-bold tabular-nums">{counts[k]}</div>
                <div className="mt-1"><Pill severity={k} /></div>
              </div>
            ))}
          </div>
          <p className="mt-4 text-sm text-muted">
            Each signal is scored by how much of the time it spent in its normal, watch and alert zones. Engine warm-up is excluded from temperature checks.
          </p>
          {missing.length > 0 && <p className="mt-2 text-sm text-pill-watch-fg">Not scored (no data): {missing.map((m) => m.label.toLowerCase()).join(', ')}.</p>}
        </section>
      </div>

      <section className="card overflow-hidden">
        <div className="border-b border-border px-5 py-4 sm:px-6"><h2 className="text-lg font-semibold">Signals and the ranges used</h2></div>
        <ul className="divide-y divide-border">
          {scan.signals.map((s) => {
            const cfg = SIGNALS[s.key];
            const f = (v: number) => fmtNum(toDisplay(s.key, v, settings), s.key);
            return (
              <li key={s.key} className="grid gap-x-6 gap-y-3 px-5 py-4 sm:px-6 md:grid-cols-[1.25fr_1.5fr_1fr_auto] md:items-center">
                <div>
                  <div className="font-medium">{cfg.label}</div>
                  <div className="mt-0.5 text-xs text-muted">{cfg.plain}</div>
                  <div className="mt-1 text-[11px] text-subtle">{rangeSummary(s.key, settings)}</div>
                </div>
                <RangeBar sig={s} settings={settings} />
                <div className="text-sm">
                  {s.available ? (
                    <>
                      <div className="font-display text-xl font-semibold tabular-nums">{f(s.avg)} <span className="text-sm font-normal text-muted">{unitFor(s.key, settings)}</span></div>
                      <div className="text-xs text-muted">min {f(s.min)} · max {f(s.max)}</div>
                      <TimeInBand s={s} />
                    </>
                  ) : <span className="text-muted">No data in this log</span>}
                </div>
                <div className="md:justify-self-end">
                  {!s.available ? <Pill severity="none" /> : !s.scored ? <Pill severity="none" label="Context" /> : <Pill severity={s.severity} />}
                </div>
              </li>
            );
          })}
        </ul>
      </section>

      {scan.mixture && (
        <section className="card p-5 sm:p-6">
          <div className="flex flex-wrap items-start justify-between gap-3">
            <div>
              <h2 className="text-lg font-semibold">Fuel mixture <span className="ml-2 align-middle text-xs font-medium text-muted">tuning indicator, not scored</span></h2>
              <p className="mt-1 max-w-2xl text-sm text-muted">{SIGNALS.afr.plain}</p>
            </div>
            <div className="text-right">
              <div className="font-display text-3xl font-bold tabular-nums">{scan.mixture.median.toFixed(1)}<span className="text-base font-normal text-muted"> : 1</span></div>
              <div className="text-xs text-muted">median while running</div>
            </div>
          </div>
          <div className="mt-4 flex h-2.5 w-full overflow-hidden rounded-full bg-surface3">
            <div className="bg-primary" style={{ width: `${scan.mixture.pctRich}%` }} />
            <div className="bg-sev-normal" style={{ width: `${scan.mixture.pctInRange}%` }} />
            <div className="bg-sev-watch" style={{ width: `${scan.mixture.pctLean}%` }} />
          </div>
          <div className="mt-2 flex flex-wrap gap-x-5 gap-y-1 text-xs text-muted">
            <span>{Math.round(scan.mixture.pctRich)}% richer than 12.5:1</span><span>{Math.round(scan.mixture.pctInRange)}% in range</span><span>{Math.round(scan.mixture.pctLean)}% leaner than 15.5:1</span>
          </div>
          <p className="mt-3 text-xs text-subtle">Petrol engines aim for about 14.7:1. Scale and fuel type are unverified, so this is shown for information only and never changes the score.</p>
        </section>
      )}

      <ExplainCard title="Explain this report" fetcher={fetcher} level={settings.explainLevel} onLevel={(l) => setSettings({ explainLevel: l })}
        onLoaded={setExplanation} resetKey={scan.id} />

      <p className="text-center text-xs text-subtle">This report reflects only the uploaded log. It is not a mechanic's diagnosis, and the ranges are generic defaults.</p>
    </div>
  );
}
