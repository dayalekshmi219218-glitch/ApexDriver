"""Generates src/theme.css from one token table and checks WCAG contrast. Run: python3 scripts/gen-theme.py"""
import sys
def rgb(h): h=h.lstrip('#'); return tuple(int(h[i:i+2],16) for i in (0,2,4))
def lum(h):
    f=lambda c:(c/255)/12.92 if c/255<=0.03928 else ((c/255+0.055)/1.055)**2.4
    r,g,b=rgb(h); return 0.2126*f(r)+0.7152*f(g)+0.0722*f(b)
def cr(a,b):
    la,lb=sorted([lum(a),lum(b)],reverse=True); return (la+0.05)/(lb+0.05)

LIGHT=dict(bg='#F7F6FB',surface='#FFFFFF',surface2='#F1EFF8',surface3='#EBE8F3',border='#DAD7E7',
  text='#1A1825',muted='#4A4760',subtle='#7A7790',primary='#5B3CD6',primaryContrast='#FFFFFF',
  primarySoft='#E8E1FF',onPrimarySoft='#1B0A5E',accent='#00695C',accentSoft='#C8F3EA',
  sevNormal='#1B8A5A',sevWatch='#C77700',sevAlert='#D93A3F',sevNone='#8A87A0',
  pillNormalBg='#E3F4EB',pillNormalFg='#166B43',pillWatchBg='#FFF0D9',pillWatchFg='#8A4B00',
  pillAlertBg='#FEE4E2',pillAlertFg='#B42318',pillNoneBg='#ECEAF2',pillNoneFg='#5B5870')
DARK=dict(bg='#0F0E15',surface='#17161F',surface2='#1D1C27',surface3='#272633',border='#2E2C3F',
  text='#E7E5F1',muted='#B3B0C7',subtle='#8E8BA3',primary='#C6B8FF',primaryContrast='#2B168F',
  primarySoft='#43329E',onPrimarySoft='#E8E1FF',accent='#5FD9C6',accentSoft='#005046',
  sevNormal='#34D399',sevWatch='#FBBF24',sevAlert='#F87171',sevNone='#8A87A0',
  pillNormalBg='#12372A',pillNormalFg='#6EE7B7',pillWatchBg='#3A2D0B',pillWatchFg='#FCD34D',
  pillAlertBg='#3F1A1A',pillAlertFg='#FCA5A5',pillNoneBg='#2A2937',pillNoneFg='#B7B4CC')

def kebab(s):
    out=''
    for ch in s: out+=('-'+ch.lower()) if ch.isupper() else ch
    return out
def block(sel,T):
    lines=[f'{sel} {{']
    for k,v in T.items(): lines.append('  --%s: %d %d %d;'%((kebab(k),)+rgb(v)))
    lines.append('}'); return '\n'.join(lines)

bad=0
def chk(mode,name,a,b,need):
    global bad
    v=cr(a,b); ok=v>=need
    if not ok: bad+=1
    print(f"  {'ok ' if ok else 'LOW'} {v:5.2f}  [{mode}] {name} (need {need})")
for mode,T in (('light',LIGHT),('dark',DARK)):
    chk(mode,'text on bg',T['text'],T['bg'],4.5); chk(mode,'text on surface',T['text'],T['surface'],4.5)
    chk(mode,'muted on surface',T['muted'],T['surface'],4.5); chk(mode,'muted on bg',T['muted'],T['bg'],4.5)
    chk(mode,'muted on surface2',T['muted'],T['surface2'],4.5)
    chk(mode,'primary text on surface',T['primary'],T['surface'],4.5); chk(mode,'primary text on bg',T['primary'],T['bg'],4.5)
    chk(mode,'primaryContrast on primary',T['primaryContrast'],T['primary'],4.5)
    chk(mode,'onPrimarySoft on primarySoft',T['onPrimarySoft'],T['primarySoft'],4.5)
    chk(mode,'accent text on surface',T['accent'],T['surface'],4.5)
    for s in ('Normal','Watch','Alert','None'):
        chk(mode,f'pill {s} fg on bg',T[f'pill{s}Fg'],T[f'pill{s}Bg'],4.5)
        chk(mode,f'sev{s} graphic on surface',T[f'sev{s}'],T['surface'],3.0)
css='/* GENERATED by scripts/gen-theme.py - edit the token table there, not this file. Values are R G B triplets. */\n'
css+=block(':root',LIGHT)+'\n\n'+block('.dark',DARK)+'\n'
open('src/theme.css','w').write(css)
print('written src/theme.css |','CONTRAST OK' if bad==0 else f'{bad} CONTRAST FAILURES')
sys.exit(1 if bad else 0)
