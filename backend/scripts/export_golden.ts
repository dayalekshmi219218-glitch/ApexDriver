/**
 * Exports golden vectors from the FRONTEND scorer so the Python scorer can be proven identical to it.
 *
 *   cd <frontend project>            # needs `tsx` (already a devDependency there)
 *   FRONTEND_DIR=$PWD npx tsx scripts/export_golden.mts  > <backend>/tests/golden/scoring_golden.json
 */
import path from 'node:path';

const FRONTEND = path.resolve(process.env.FRONTEND_DIR ?? '../apexdriver-web');
const { seedDemo } = await import(path.join(FRONTEND, 'src/lib/synth.ts'));
const { scoreSample } = await import(path.join(FRONTEND, 'src/lib/scoring.ts'));
const { SIGNALS, SCORED_KEYS } = await import(path.join(FRONTEND, 'src/lib/config.ts'));

const NOW = Date.UTC(2026, 9, 17, 12, 0, 0);
const demo = seedDemo(NOW);

const grid: number[] = [];
for (let v = -30; v <= 9000; v += v < 200 ? 0.5 : v < 1000 ? 7.3 : 41.9) grid.push(Math.round(v * 100) / 100);

const samples: Record<string, { values: number[]; scores: number[] }> = {};
for (const key of SCORED_KEYS) {
  const cfg = SIGNALS[key].cfg;
  samples[key] = { values: grid, scores: grid.map((v) => scoreSample(v, cfg)) };
}

const scans = demo.scans.map((s: any) => ({
  id: s.id,
  series: s.series,
  expected: {
    score: s.score, severity: s.severity, scoredSignals: s.scoredSignals, totalSignals: s.totalSignals,
    states: s.states, mixture: s.mixture, signals: s.signals,
  },
}));

process.stdout.write(JSON.stringify({ note: 'generated by scripts/export_golden.ts from the frontend scorer', samples, scans }));
